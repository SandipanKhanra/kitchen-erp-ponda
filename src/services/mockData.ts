export function buildInitial15DayMenu(centerId = 'center_ponda'): FifteenDayMenuPlan {
  const startDate = '2026-11-20'; // Day 1 will hit Utpanna Ekadashi for live testing!
  const start = new Date(startDate);

  const days: Record<number, any> = {};

  for (let d = 1; d <= 15; d++) {
    const currentDate = new Date(start);
    currentDate.setDate(currentDate.getDate() + (d - 1));
    const dateStr = formatDateISO(currentDate);

    const isEkadashi = isEkadashiOrFastingDate(dateStr);
    const occasion = getVaishnavaOccasionForDate(dateStr);

    if (isEkadashi) {
      // Automatic Ekadashi Menu selection!
      days[d] = {
        dayNumber: d,
        date: dateStr,
        isEkadashi: true,
        isFasting: true,
        occasionTitle: occasion?.name || 'Ekadashi Vrata',
        breakfast: {
          recipeIds: ['rec_ekadashi_sabudana'],
          headcount: 90,
        },
        lunch: {
          patternId: 'pat_3',
          recipeIds: ['rec_ekadashi_sama_paneer', 'rec_ekadashi_fruits'],
          headcount: 140,
        },
        dinner: {
          recipeIds: ['rec_ekadashi_fruits'],
          headcount: 85,
        },
        notes: 'Grain-fasting observed strictly. No rice, wheat, dal, or beans.',
      };
    } else {
      // Normal rotation menu with alternating dishes
      days[d] = {
        dayNumber: d,
        date: dateStr,
        isEkadashi: false,
        isFasting: false,
        occasionTitle: 'Regular Service',
        breakfast: {
          recipeIds: ['rec_khichdi'],
          headcount: 100,
        },
        lunch: {
          patternId: 'pat_1',
          recipeIds: ['rec_rajbhog_rice_dal', 'rec_sweet_rice'],
          headcount: 150,
        },
        dinner: {
          patternId: 'pat_2',
          recipeIds: ['rec_matar_paneer'],
          headcount: 110,
        },
      };
    }
  }

  return {
    id: `plan_${centerId}_cycle_1`,
    centerId,
    title: '15-Day Master Cycle (Nov 20 — Dec 04)',
    startDate: '2026-11-20',
    endDate: '2026-12-04',
    status: 'pending_approval',
    days,
    createdBy: 'admin_ponda_1', // Created by Krishna Chaitanya Dasa
    createdByName: 'Krishna Chaitanya Dasa (Admin)',
    createdByRole: 'admin',
    // approvedBy is undefined -> Requires Govinda Priya Dasa (admin 2) to approve!
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  };
}
